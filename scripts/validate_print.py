def main() -> None:
    parser = argparse.ArgumentParser(description="Validate print readiness from a *_summary.json mesh report.")
    parser.add_argument("summary", type=Path, help="Path to *_summary.json generated by make_model.py.")
    parser.add_argument(
        "--slicer-profile",
        choices=tuple(PROFILES.keys()),
        default=DEFAULT_PROFILE,
        help="Local slicer-readiness threshold profile (no external slicer required).",
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Alias for --slicer-profile fdm unless profile was explicitly set.",
    )
    parser.add_argument("--require-watertight", action="store_true", help="Fail when mesh is not watertight.")
    parser.add_argument(
        "--max-non-manifold-edges",
        type=int,
        default=None,
        help="Maximum allowed non-manifold edge count (default: 0).",
    )
    parser.add_argument(
        "--max-degenerate-faces",
        type=int,
        default=None,
        help="Maximum allowed degenerate face count (default: 0).",
    )
    parser.add_argument("--min-dimension", type=float, default=None, help="Minimum allowed bbox side length.")
    parser.add_argument("--max-dimension", type=float, default=None, help="Maximum allowed bbox side length.")
    parser.add_argument("--min-volume", type=float, default=None, help="Minimum required mesh volume.")
    parser.add_argument(
        "--format",
        choices=("json", "text"),
        default="json",
        help="Output format (default: json).",
    )
    parser.add_argument(
        "--slicer-check-cmd",
        default=None,
        help="Optional external slicer check command template. Supports {summary} and {model} placeholders.",
    )
    parser.add_argument(
        "--model-path",
        type=Path,
        default=None,
        help="Model file path used for {model} in --slicer-check-cmd.",
    )
    parser.add_argument(
        "--slicer-timeout-seconds",
        type=float,
        default=120.0,
        help="Timeout for the external slicer check command (default: 120).",
    )
    parser.add_argument(
        "--include-slicer-template",
        action="store_true",
        help="Include a suggested slicer-check command template in the report.",
    )
    args = parser.parse_args()

    summary_path = args.summary.resolve()
    summary = json.loads(summary_path.read_text(encoding="utf-8-sig"))
    profile_name, thresholds = _effective_thresholds(args)
    report = validate_summary(
        summary,
        profile_name=profile_name,
        **thresholds,
    )
    slicer_context = _build_slicer_context(summary_path, args.model_path)
    if args.include_slicer_template:
        report["slicer_check_template"] = slicer_check_template(slicer_context)
    if args.slicer_check_cmd:
        report["slicer_check"] = run_slicer_check(
            args.slicer_check_cmd,
            context=slicer_context,
            timeout_seconds=args.slicer_timeout_seconds,
        )
        report["passed"] = report["passed"] and report["slicer_check"]["passed"]

    if args.format == "text":
        print(format_text_report(report))
    else:
        print(json.dumps(report, indent=2))

    if not report["passed"]:
        raise SystemExit(1)


def validate_summary(
    summary: dict[str, Any],
    *,
    profile_name: str = DEFAULT_PROFILE,
    require_watertight: bool,
    max_non_manifold_edges: int,
    max_degenerate_faces: int,
    min_dimension: float | None,
    max_dimension: float | None,
    min_volume: float | None,
    min_base_thickness: float | None = None,
    min_wall_thickness: float | None = None,
) -> dict[str, Any]:
    mesh_quality = summary.get("mesh_quality")
    if not isinstance(mesh_quality, dict):
        raise ValueError("summary does not contain a mesh_quality object")

    checks: list[dict[str, Any]] = []

    if require_watertight:
        watertight = mesh_quality.get("is_watertight")
        checks.append(_result("watertight", watertight is True, actual=watertight, expected=True))

    non_manifold_edges = _as_int(mesh_quality.get("non_manifold_edge_count"))
    checks.append(
        _result(
            "max_non_manifold_edges",
            non_manifold_edges is not None and non_manifold_edges <= max_non_manifold_edges,
            actual=non_manifold_edges,
            expected=max_non_manifold_edges,
        )
    )

    degenerate_faces = _as_int(mesh_quality.get("degenerate_face_count"))
    checks.append(
        _result(
            "max_degenerate_faces",
            degenerate_faces is not None and degenerate_faces <= max_degenerate_faces,
            actual=degenerate_faces,
            expected=max_degenerate_faces,
        )
    )

    dimensions = _dimensions(mesh_quality.get("bounds"))
    if min_dimension is not None:
        smallest = min(dimensions) if dimensions is not None else None
        checks.append(
            _result(
                "min_dimension",
                smallest is not None and smallest >= min_dimension,
                actual=smallest,
                expected=min_dimension,
            )
        )
    if max_dimension is not None:
        largest = max(dimensions) if dimensions is not None else None
        checks.append(
            _result(
                "max_dimension",
                largest is not None and largest <= max_dimension,
                actual=largest,
                expected=max_dimension,
            )
        )

    if min_volume is not None:
        volume = _as_float(mesh_quality.get("volume"))
        checks.append(_result("min_volume", volume is not None and volume >= min_volume, actual=volume, expected=min_volume))

    # Optional hints can come from mesh_quality or top-level summary.
    base_thickness = _hint_value(summary, mesh_quality, "base_thickness", "base_thickness_hint", "min_base_thickness")
    if min_base_thickness is not None:
        checks.append(
            _result(
                "min_base_thickness",
                base_thickness is not None and base_thickness >= min_base_thickness,
                actual=base_thickness,
                expected=min_base_thickness,
            )
        )

    wall_thickness = _hint_value(summary, mesh_quality, "wall_thickness", "wall_thickness_hint", "min_wall_thickness")
    if min_wall_thickness is not None:
        checks.append(
            _result(
                "min_wall_thickness",
                wall_thickness is not None and wall_thickness >= min_wall_thickness,
                actual=wall_thickness,
                expected=min_wall_thickness,
            )
        )

    passed = all(item["passed"] for item in checks)
    return {
        "passed": passed,
        "profile": profile_name,
        "summary_path": summary.get("summary_path"),
        "thresholds": {
            "require_watertight": require_watertight,
            "max_non_manifold_edges": max_non_manifold_edges,
            "max_degenerate_faces": max_degenerate_faces,
            "min_dimension": min_dimension,
            "max_dimension": max_dimension,
            "min_volume": min_volume,
            "min_base_thickness": min_base_thickness,
            "min_wall_thickness": min_wall_thickness,
        },
        "checks": checks,
    }


def format_text_report(report: dict[str, Any]) -> str:
    lines = [f"PASS={report['passed']}", f"PROFILE={report.get('profile', DEFAULT_PROFILE)}"]
    for check in report["checks"]:
        status = "PASS" if check["passed"] else "FAIL"
        label = check.get("label", check["name"])
        recommendation = check.get("recommendation")
        line = f"{status:4} {label}: actual={check['actual']} expected={check['expected']}"
        if recommendation:
            line += f" | {recommendation}"
        lines.append(line)
    slicer_check = report.get("slicer_check")
    if isinstance(slicer_check, dict):
        lines.append(
            "SLICER_CHECK="
            + ("PASS" if slicer_check.get("passed") else "FAIL")
            + f" command={slicer_check.get('command')}"
        )
        if slicer_check.get("error"):
            lines.append(f"SLICER_ERROR={slicer_check['error']}")
    template = report.get("slicer_check_template")
    if isinstance(template, str):
        lines.append(f"SLICER_TEMPLATE={template}")
    return "\n".join(lines)


def _result(name: str, passed: bool, *, actual: Any, expected: Any) -> dict[str, Any]:
    return {
        "name": name,
        "passed": passed,
        "actual": actual,
        "expected": expected,
        "label": CHECK_META.get(name, {}).get("label", name),
        "recommendation": CHECK_META.get(name, {}).get("recommendation"),
    }


