def _dimensions(bounds: Any) -> tuple[float, float, float] | None:
    if not isinstance(bounds, (list, tuple)) or len(bounds) != 2:
        return None
    low, high = bounds
    if not isinstance(low, (list, tuple)) or not isinstance(high, (list, tuple)):
        return None
    if len(low) != 3 or len(high) != 3:
        return None
    dims: list[float] = []
    for min_v, max_v in zip(low, high):
        min_f = _as_float(min_v)
        max_f = _as_float(max_v)
        if min_f is None or max_f is None:
            return None
        dims.append(max_f - min_f)
    return (dims[0], dims[1], dims[2])


def _as_int(value: Any) -> int | None:
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, float) and math.isfinite(value) and value.is_integer():
        return int(value)
    return None


def _as_float(value: Any) -> float | None:
    if isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        value = float(value)
        if math.isfinite(value):
            return value
    return None


def _effective_thresholds(args: argparse.Namespace) -> tuple[str, dict[str, Any]]:
    profile_name = args.slicer_profile
    if args.strict and profile_name == DEFAULT_PROFILE:
        profile_name = "fdm"
    profile = dict(PROFILES[profile_name])

    # CLI flags can override profile defaults.
    if args.require_watertight:
        profile["require_watertight"] = True
    if args.max_non_manifold_edges is not None:
        profile["max_non_manifold_edges"] = args.max_non_manifold_edges
    if args.max_degenerate_faces is not None:
        profile["max_degenerate_faces"] = args.max_degenerate_faces
    if args.min_dimension is not None:
        profile["min_dimension"] = args.min_dimension
    if args.max_dimension is not None:
        profile["max_dimension"] = args.max_dimension
    if args.min_volume is not None:
        profile["min_volume"] = args.min_volume
    return profile_name, profile


def _hint_value(summary: dict[str, Any], mesh_quality: dict[str, Any], *keys: str) -> float | None:
    for source in (mesh_quality, summary):
        for key in keys:
            value = _as_float(source.get(key))
            if value is not None:
                return value
    return None


def _build_slicer_context(summary_path: Path, model_path: Path | None) -> dict[str, str]:
    resolved_model = model_path.resolve() if model_path is not None else _infer_model_path(summary_path)
    return {
        "summary": str(summary_path),
        "model": str(resolved_model) if resolved_model is not None else "",
    }


def _infer_model_path(summary_path: Path) -> Path | None:
    if summary_path.name.endswith("_summary.json"):
        candidate = summary_path.with_name(summary_path.name[: -len("_summary.json")] + ".stl")
        if candidate.exists():
            return candidate.resolve()
    return None


def slicer_check_template(context: dict[str, str]) -> str:
    return (
        'prusa-slicer-console.exe --export-gcode --load "printer_config.ini" '
        '--output "output.gcode" "{model}"'
    ).format_map(context)


def run_slicer_check(command_template: str, *, context: dict[str, str], timeout_seconds: float) -> dict[str, Any]:
    try:
        command = command_template.format_map(context)
    except KeyError as exc:
        return {
            "passed": False,
            "command_template": command_template,
            "error": f"unknown placeholder: {exc}",
        }

    if "{model}" in command_template and not context.get("model"):
        return {
            "passed": False,
            "command_template": command_template,
            "error": "model path is required for {model}; pass --model-path or place <name>.stl next to *_summary.json",
        }

    try:
        args = shlex.split(command, posix=False)
    except ValueError as exc:
        return {
            "passed": False,
            "command": command,
            "error": f"invalid command syntax: {exc}",
        }

    try:
        completed = subprocess.run(args, capture_output=True, text=True, timeout=timeout_seconds, check=False)
    except FileNotFoundError as exc:
        return {
            "passed": False,
            "command": command,
            "error": f"command not found: {exc}",
        }
    except OSError as exc:
        return {
            "passed": False,
            "command": command,
            "error": f"failed to run command: {exc}",
        }

    return {
        "passed": completed.returncode == 0,
        "command": command,
        "returncode": completed.returncode,
        "stdout": completed.stdout,
        "stderr": completed.stderr,
    }


if __name__ == "__main__":
    main()
